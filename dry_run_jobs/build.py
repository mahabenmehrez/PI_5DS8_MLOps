"""Dry run "build" of the Setup Agent (roadmap 5.8 / 7.3, option c): `make -C <folder> all SAMPLE=1` on a copy of the
repo with the generated files. Lives in dry_run_jobs/ at the root, like every dry-run kind (roadmap 5.2).

The real repo is never touched: the repo is copied to a temp folder, the generated files are written there, and
make runs on the first 200 rows of the data. No Docker (the Docker sandbox of the Builder stays optional).

    DRY_RUN=1 python agents/setup/dry_run_jobs/build.py inputs.json      # prints the result as JSON
inputs.json: {"root": ".", "files": {path: text}, "makefile": "baseline/Makefile", "timeout_s": 600, "fresh_venv": false,
              "update_own": [paths the agent may rewrite on a rebuild], "marker": "# Generated by builder-agent..."}
"""
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

SKIP = {".git", ".setup", ".venv", "venv", "mlruns", "mlartifacts", "__pycache__", ".pytest_cache", ".cache",
        ".tools", "logs", "node_modules", ".idea", ".vscode"}
# outside the repo (a venv inside a synced folder like OneDrive breaks); SETUP_AGENT_CACHE moves it
CACHE = Path(os.environ.get("SETUP_AGENT_CACHE", Path.home() / ".cache" / "setup-agent"))
KEEP_VENVS = 3                          # isolated venvs kept for reuse (a few hundred MB each)

# error class -> what in the log shows it (first match wins, most specific first)
ERROR_CLASSES = [
    ("BrokenEnvironment", r"Could not install packages due to an OSError"),
    ("ModuleNotFoundError", r"ModuleNotFoundError: No module named '([\w.]+)'"),
    ("ImportError", r"ImportError: cannot import name '?(\w+)'?"),
    ("ResolutionImpossible", r"ResolutionImpossible|No matching distribution found for (\S+)"),
    ("SchemaError", r"schema failure"),
    ("FileNotFoundError", r"FileNotFoundError: .*?'([^']+)'"),
    ("OutOfMemory", r"\bKilled\b|exit status 137|Error 137"),
    ("TestFailure", r"(\d+) failed"),
    ("SyntaxError", r"SyntaxError"),
]
STAGE = re.compile(r"make: \*\*\* \[(?:[^:\]]*:\d+: )?(\w+)\] Error")


def classify(log: str) -> tuple[str, str | None]:
    """(error class, detail): detail is the missing module, package or file when the log names it."""
    for name, pattern in ERROR_CLASSES:
        m = re.search(pattern, log)
        if m:
            return name, (m.group(1) if m.groups() else None)
    return "Error", None


def install_key(work: Path) -> str:
    """What decides what `make install` installs: every Makefile and requirements file of the copy."""
    h = hashlib.sha256()
    for p in sorted(work.rglob("*")):
        if p.is_file() and (p.name == "Makefile" or (p.name.startswith("requirements") and p.suffix == ".txt")):
            h.update(p.relative_to(work).as_posix().encode() + b"\0" + p.read_bytes() + b"\0")
    return h.hexdigest()[:16]


def _python(key: str, fresh: bool = False) -> str:
    """An ISOLATED venv (no system site-packages) for this install set: the dry run sees only what `make install`
    installs, so a dependency the Makefile forgets fails here instead of hiding behind the machine's packages.
    Reused while the install set is the same (fast); pip's own cache keeps a new one quick.
    fresh: delete it first (the fix for BrokenEnvironment, e.g. an install that was interrupted)."""
    venv = CACHE / f"venv-{key}"
    py = venv / ("Scripts/python.exe" if os.name == "nt" else "bin/python")
    if fresh and venv.exists():
        shutil.rmtree(venv)
    if not py.exists():
        subprocess.run([sys.executable, "-m", "venv", str(venv)], check=True)
    os.utime(venv)
    old = sorted(CACHE.glob("venv-*"), key=lambda p: p.stat().st_mtime, reverse=True)[KEEP_VENVS:]
    for v in old:
        shutil.rmtree(v, ignore_errors=True)
    return str(py)


_CANNOT_IMPORT = re.compile(r"cannot import name '([\w]+)' from '([\w.]+)'")


def installed_versions(python: str) -> dict[str, str]:
    """{pip name (lowercase): version} installed in the dry-run venv: what the diagnosis may pin against."""
    try:
        r = subprocess.run([python, "-m", "pip", "list", "--format=json"], capture_output=True, text=True,
                           timeout=60, env={**os.environ, "PIP_DISABLE_PIP_VERSION_CHECK": "1"})
        return {p["name"].lower(): p["version"] for p in json.loads(r.stdout or "[]")}
    except Exception:  # noqa: BLE001 - only a hint: the diagnosis works without it
        return {}


def import_hint(python: str, log: str) -> dict | None:
    """For "cannot import name X from M": the names M really has that look like X (difflib). A close match
    (LogisticRegresion -> LogisticRegression) means a misspelling in the project's code, not a version problem."""
    m = _CANNOT_IMPORT.findall(log)
    if not m:
        return None
    name, module = m[-1]
    code = ("import difflib, importlib, json, sys; m = importlib.import_module(sys.argv[2]); "
            "print(json.dumps(difflib.get_close_matches(sys.argv[1], dir(m), n=3, cutoff=0.85)))")
    try:
        r = subprocess.run([python, "-c", code, name, module], capture_output=True, text=True, timeout=120)
        return {"name": name, "module": module, "close": json.loads(r.stdout.strip().splitlines()[-1])}
    except Exception:  # noqa: BLE001
        return None


def run(root: str, files: dict[str, str], timeout_s: int = 600, fresh_venv: bool = False,
        makefile: str = "Makefile", update_own: tuple = (), marker: str = "") -> dict:
    """update_own (request.rebuild): these paths replace the existing file when it was generated by the agent
    (its first line is `marker`), as write_team will do: the dry run checks what will really be used."""
    start = time.time()
    python = None
    with tempfile.TemporaryDirectory(prefix="setup-dryrun-") as tmp:
        work = Path(tmp) / "repo"
        shutil.copytree(root, work, ignore=lambda d, names: [n for n in names if n in SKIP])
        for rel, text in files.items():
            path = work / rel
            if path.exists():
                first = path.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").split("\n", 1)[0]
                if not (rel in update_own and marker and first.strip() == marker.strip()):
                    continue                    # the team's file stays: the dry run checks what will really be used
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
        env = {**os.environ, "DRY_RUN": "1", "MLFLOW_TRACKING_URI": (work / ".setup" / "mlruns").as_uri(),
               "PIP_DISABLE_PIP_VERSION_CHECK": "1"}
        try:
            python = _python(install_key(work), fresh_venv)
            r = subprocess.run(["make", "-C", str(Path(makefile).parent), "-f", Path(makefile).name, "all",
                                "SAMPLE=1", f"PYTHON={python}"], cwd=work, env=env,
                               capture_output=True, text=True, timeout=timeout_s)
            log, code = r.stdout + r.stderr, r.returncode
        except subprocess.TimeoutExpired as e:
            log = (e.stdout or b"").decode(errors="replace") if isinstance(e.stdout, bytes) else (e.stdout or "")
            return {"ok": False, "stage": "all", "error_class": "Timeout", "detail": f"{timeout_s}s",
                    "log": log[-20000:], "seconds": round(time.time() - start, 1)}
    if code == 0:
        return {"ok": True, "stage": None, "error_class": None, "detail": None, "log": log[-20000:],
                "seconds": round(time.time() - start, 1)}
    m = STAGE.search(log)
    error_class, detail = classify(log)
    if error_class != "BrokenEnvironment" and "cannot open shared object file" in log and str(CACHE) in log:
        # a library inside the dry-run venv itself is missing: an install that was cut short (full disk, killed
        # run), not the project's fault; the rule recreates the venv once
        error_class, detail = "BrokenEnvironment", "a compiled library of the dry-run venv is missing"
    return {"ok": False, "stage": m.group(1) if m else "all", "error_class": error_class, "detail": detail,
            "log": log[-20000:], "seconds": round(time.time() - start, 1),
            "installed": installed_versions(python) if python else {},
            "python": ".".join(map(str, sys.version_info[:3])),        # the dry-run venv is made from this Python
            "import_hint": import_hint(python, log) if python else None}


if __name__ == "__main__":
    inputs = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    print(json.dumps(run(inputs.get("root", "."), inputs["files"], int(inputs.get("timeout_s", 600)),
                         bool(inputs.get("fresh_venv")), inputs.get("makefile", "Makefile"),
                         tuple(inputs.get("update_own", ())), inputs.get("marker", ""))))
